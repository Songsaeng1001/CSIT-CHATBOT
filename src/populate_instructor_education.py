def run():
    updated, missing = 0, []
    with db_session() as conn:
        for staff_id, education in EDUCATION_DATA.items():
            cur = conn.execute(
                "UPDATE instructors SET education = ? WHERE staff_id = ?",
                (education, staff_id),
            )
            if cur.rowcount > 0:
                updated += 1
            else:
                missing.append(staff_id)

    print(f" อัปเดตวุฒิการศึกษาแล้ว {updated}/{len(EDUCATION_DATA)} ท่าน")
    if missing:
        print(f"  ไม่พบ staff_id เหล่านี้ในตาราง instructors (เช็คว่า sqlite ยังไม่ได้ seed หรือ staff_id เปลี่ยน):")
        for s in missing:
            print(f"   - {s}")


if __name__ == "__main__":
    run()